// Bundles the ORIGINAL mylecture-agent LectureGen pipeline into the app.
//   node scripts/build-lecturegen.mjs [path/to/mylecture-agent]
// Output (committed, so the app builds without the agent repo):
//   electron/lecturegen/src/lecturegen.mjs   the bundled stages
//   electron/lecturegen/src/prompts/          original system prompts (verbatim)
//   electron/lecturegen/resources/            original themes, teaching styles, contract, runtime
//   electron/assets/world-basemap.svg         bundled Natural Earth basemap
// Swapped at bundle time (nothing else is modified):
//   utils/llm_model, repair-model -> app engine bridge
//   playwright                    -> Electron offscreen windows
//   env.js                        -> no-op (the app sets process.env itself)
//   sharp                         -> stub (image fetching is disabled)
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const agent = path.resolve(process.argv[2] || path.join(appRoot, "..", "mylecture-agent"));
const outDir = path.join(appRoot, "electron", "lecturegen");
const shims = path.join(appRoot, "lecturegen", "shims");

const swap = {
  [path.join(agent, "src", "utils", "llm_model.ts")]: path.join(shims, "llm_model.js"),
  [path.join(agent, "src", "repair-model.ts")]: path.join(shims, "repair-model.js"),
  [path.join(agent, "src", "env.ts")]: path.join(shims, "env.js"),
};

const plugin = {
  name: "mylecture-swap",
  setup(b) {
    b.onResolve({ filter: /^playwright$/ }, () => ({ path: path.join(shims, "playwright.js") }));
    b.onResolve({ filter: /^sharp$/ }, () => ({ path: path.join(shims, "sharp.js") }));
    b.onResolve({ filter: /^dotenv$/ }, () => ({ path: path.join(shims, "env.js") }));
    b.onResolve({ filter: /^electron$/ }, () => ({ path: "electron", external: true }));
    b.onResolve({ filter: /^\.\.?\// }, (args) => {
      let p = path.resolve(args.resolveDir, args.path);
      const ts = p.replace(/\.js$/, ".ts");
      if (swap[ts]) return { path: swap[ts] };
      if (swap[p]) return { path: swap[p] };
      return undefined;
    });
  },
};

fs.mkdirSync(path.join(outDir, "src"), { recursive: true });
fs.writeFileSync(path.join(shims, "env.js"), "export default { config() {} };\nexport function loadRepositoryEnv() {}\n");
fs.writeFileSync(path.join(shims, "sharp.js"), "export default function sharp() { throw new Error('Image processing is not available in MyLecture.'); }\n");

await build({
  entryPoints: [path.join(appRoot, "lecturegen", "entry.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: path.join(outDir, "src", "lecturegen.mjs"),
  plugins: [plugin],
  external: ["electron"],
  banner: {
    js: [
      "// GENERATED by scripts/build-lecturegen.mjs from mylecture-agent. Do not edit.",
      "import { createRequire as __mlCreateRequire } from 'node:module';",
      "const require = __mlCreateRequire(import.meta.url);",
    ].join("\n"),
  },
  logLevel: "warning",
});

// Copy resources verbatim.
const copyDir = (from, to) => {
  fs.rmSync(to, { recursive: true, force: true });
  fs.cpSync(from, to, { recursive: true });
};
copyDir(path.join(agent, "src", "prompts"), path.join(outDir, "src", "prompts"));
copyDir(path.join(agent, "resources"), path.join(outDir, "resources"));
fs.copyFileSync(path.join(shims, "page-preload.cjs"), path.join(outDir, "src", "page-preload.cjs"));
fs.mkdirSync(path.join(appRoot, "electron", "assets"), { recursive: true });
fs.copyFileSync(path.join(agent, "assets", "world-basemap.svg"), path.join(appRoot, "electron", "assets", "world-basemap.svg"));
console.log("Bundled LectureGen from", agent);
